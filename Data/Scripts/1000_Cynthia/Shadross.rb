def Undertale(golden = false)
  UndertaleShopSetup(golden)
  scene = Undertale_Scene.new
  playingBGS = nil
  playingBGM = nil
  if $game_system && $game_system.is_a?(Game_System)
    playingBGS = $game_system.getPlayingBGS
    playingBGM = $game_system.getPlayingBGM
    $game_system.bgm_pause
    $game_system.bgs_pause
  end
  result = UndertaleCommand(scene, golden)
  scene.pbEndBattle
  if $game_system && $game_system.is_a?(Game_System)
    $game_system.bgm_resume(playingBGM)
    $game_system.bgs_resume(playingBGS)
  end
  Input.update
  return result
end

def UndertaleCommand(scene, golden = false)
  pbBGMPlay("Megalovania")
  pbBGMPlay("VSCalc") if golden
  loop do
    cmd = scene.UndertaleCommandMenu()
    pbSEPlay("MenuSelect")
    case cmd
    when 0    # Fight
      if $Trainer.party.length == 0
        return false
      end
      if golden
        return goldenSkeletonBattle()
      end
      $PokemonGlobal.nextBattleBack = "Lava"
      $PokemonGlobal.nextBattleBGM = nil
      if !pbTrainerBattle(:Skeleton_Dev, "Shadross", nil, false, 2)
        return true
      end
    when 1    # Act
      if !scene.UndertaleActMenu() && golden
        return goldenSkeletonBattle()
      end
    when 2    # Item
      if !scene.UndertaleItemMenu() && golden
        return goldenSkeletonBattle()
      end
    when 3    # Mercy
      if golden
        msgBox = scene.sprites["commandWindow"].sprites["msgBox"]
        msgBox.text = ""
        text = "Nuh uh"
        pbWait(1)
        for i in 0..text.length()
          msgBox.text = text[0..i]
          pbSEPlay("BattleText")
          pbWait(1)
        end
        pbWait(40)
        return goldenSkeletonBattle()
      end
      return true
    end
  end
end

def UndertaleShopSetup(golden = false)
  if $PokemonGlobal.cynthiabadgetier && $Trainer.numbadges > $PokemonGlobal.cynthiabadgetier && $PokemonGlobal.towervalues.nil?
    $PokemonBag.pbDeleteItem(:SINNOHCOIN, 999)
    if !$PokemonGlobal.pcItemStorage
      $PokemonGlobal.pcItemStorage = PCItemStorage.new
    end
    $PokemonGlobal.pcItemStorage.pbDeleteItem(:SINNOHCOIN,999)
    $PokemonGlobal.cynthiaupgradechance = 0
    $PokemonGlobal.cynthiabadgetier = $Trainer.numbadges
    $PokemonGlobal.cynthiachance = 1000
  end
  $PokemonGlobal.shadrossstock = SHADROSS_STOCK
  if hasEmera?(:VIPCARD)
    $PokemonGlobal.shadrossstock.each do |key, value|
      value["cost"] = ((value["cost"] + 1) / 2.0).ceil
    end
  end
  $PokemonGlobal.shadrosshints = SHADROSS_HINTS
  if golden
    $PokemonGlobal.shadrossstock = {
      :KNUCKLESANDWICH => {
        "badges" => 0,
        "cost" => 0,
        "amount" => 1,
      },
    }
    $PokemonGlobal.shadrosshints = {
      :RUN => {
        "badges" => 0,
        "cost" => 69,
        "name" => "Run",
        "hint" => "Nuh uh",
      },
    }
  end
end

class Undertale_Scene
  attr_reader   :viewport
  attr_reader   :sprites

  BLANK       = 0
  MESSAGE_BOX = 1
  COMMAND_BOX = 2

  MESSAGE_PAUSE_TIME = (Graphics.frame_rate*0.25).floor   # 1 second

  #=============================================================================
  # Updating and refreshing
  #=============================================================================
  def pbUpdate(cw=nil)
    pbGraphicsUpdate
    Input.update
    cw.update if cw
  end

  def pbGraphicsUpdate
    # Update lineup animations
    if @animations.length>0
      shouldCompact = false
      @animations.each_with_index do |a,i|
        a.update
        if a.animDone?
          a.dispose
          @animations[i] = nil
          shouldCompact = true
        end
      end
      @animations.compact! if shouldCompact
    end
    # Update other graphics
    Graphics.update
    @frameCounter += 1
    @frameCounter = @frameCounter%(Graphics.frame_rate*12/20)
  end
  #=============================================================================
  # Phases
  #=============================================================================
  def pbEndBattle()
    # Fade out all sprites
    pbBGMFade(1.0)
    pbFadeOutAndHide(@sprites)
    pbDisposeSpriteHash(@sprites)
  end

  #=============================================================================
  # Create the battle scene and its elements
  #=============================================================================
  def initialize
    @animations = []
    @frameCounter = 0
    @viewport = Viewport.new(0, 0, Graphics.width, Graphics.height)
    @viewport.z = 99999
    @sprites = {}
    # Create command window
    @sprites["commandWindow"] = UndertaleMenu.new(@viewport, 200)
    @sprites["actWindow"] = UndertaleActMenu.new(@viewport, 300)
    @sprites["actWindow"].visible = false
    @sprites["itemWindow"] = UndertaleItemMenu.new(@viewport, 300)
    @sprites["itemWindow"].visible = false
  end

  def UndertaleCommandMenu()
    cw = @sprites["commandWindow"]
    ret = -1
    loop do
      oldIndex = cw.index
      pbUpdate(cw)
      # Update selected command
      if Input.trigger?(Input::LEFT)
        cw.index = 3-((3 - cw.index + 1) % 4)
      elsif Input.trigger?(Input::RIGHT)
        cw.index = (cw.index + 1) % 4
      end
      pbSEPlay("MenuCursor") if cw.index!=oldIndex
      # Actions
      if Input.trigger?(Input::USE)                 # Confirm choice
        ret = cw.index
        break
      end
    end
    return ret
  end

  def UndertaleActMenu()
    cw = @sprites["actWindow"]
    msgBox = @sprites["commandWindow"].sprites["msgBox"]
    msgBox.text = ""
    cw.visible = true
    ret = -1
    hintactive = false
    hintitem = nil
    loop do
      if hintactive
        if Input.trigger?(Input::USE) || Input.trigger?(Input::BACK)
          return false if hintitem == :RUN
          cw.visible = true
          hintactive = false
        end
        pbUpdate(cw)
      else
        oldIndex = cw.index
        oldhintitemindex = cw.hintitemindex
        pbUpdate(cw)
        # Update selected command
        if Input.trigger?(Input::UP)
          cw.index = cw.index - 1
        elsif Input.trigger?(Input::DOWN)
          cw.index = cw.index + 1
        elsif Input.trigger?(Input::RIGHT) 
          cw.index = cw.index + 1
          cw.index = cw.index + 1
          cw.index = cw.index + 1
          cw.index = cw.index + 1
          cw.index = cw.index + 1
        elsif Input.trigger?(Input::LEFT)
          cw.index = cw.index - 1
          cw.index = cw.index - 1
          cw.index = cw.index - 1
          cw.index = cw.index - 1
          cw.index = cw.index - 1
        end
        pbSEPlay("MenuCursor") if cw.index != oldIndex || cw.hintitemindex != oldhintitemindex
        # Actions
        if Input.trigger?(Input::USE)                 # Confirm choice
             = $PokemonGlobal.shadrosshints.keys[cw.hintitemindex + cw.index]
          if !hintitem
            break
          end
          if pbCynthiaGetBadgeCount < $PokemonGlobal.shadrosshints[hintitem]["badges"]
            text = "Weak ass."
          elsif $Trainer.money < $PokemonGlobal.shadrosshints[hintitem]["cost"]
            text = "Broke ass."
